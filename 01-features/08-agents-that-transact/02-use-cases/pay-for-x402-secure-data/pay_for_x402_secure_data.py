"""Pay for Secure Data (x402) — trust-gated Strands buyer agent.

App-backend script that:
  1. Installs the Python dependencies (handled out of band by the user)
  2. Loads .env (USER_ID auto-generated by setup-env.sh on first run)
  3. Demonstrates the deterministic trust guardrail with MOCKS (no AWS, no money)
  4. Provisions the AgentCore payments stack inline:
       one Credential Provider (Coinbase CDP) -> one Manager -> one Connector
  5. Creates one EMBEDDED_CRYPTO_WALLET instrument and a spending-limit-capped
       payment session, then prints the delegated-signing + funding steps
  6. Builds the trust-gated agent (two tools + AgentCorePaymentsPlugin)
  7. Runs the agent LIVE against t54 x402-secure and the target x402 service
       (interactive prompt: Enter to spend real USDC, q to skip)
  8. Deploys the agent to AgentCore Runtime via CodeBuild and invokes it
       (interactive prompt: Enter to deploy, q to skip)
  9. Inspects the data plane (session spending limit, balance, lists)
 10. Cleanup (revoke session, delete payments resources, destroy runtime)
       (interactive prompt: Enter to clean up, q to skip)

Usage:
    python pay_for_x402_secure_data.py

Prerequisites:
    bash test/integration/setup-env.sh        # generates USER_ID, seeds .env
    cp env-sample.txt .env                    # then fill in Coinbase secrets + INSTRUMENT_EMAIL
    bash test/integration/setup-roles.sh      # creates the four IAM roles

Notebook companion: see the matching pay-for-x402-secure-data.ipynb under
06-workshops/13-AgentCore-payments/02-use-cases/pay-for-x402-secure-data/ for a
step-by-step walkthrough with markdown commentary and screenshots.

The agent is designed so that it never holds private keys. AgentCore Identity
stores wallet-provider secrets in AWS Secrets Manager under KMS encryption after
CreatePaymentCredentialProvider runs in §4. The agent runtime calls
GetResourcePaymentToken at signing time and never receives the raw secret. Every
target x402 payment is gated in code by TrustedX402ServiceGateway behind a paid
t54 x402-secure trust check.
"""

