# ── §9. Inspect the data plane ───────────────────────────────────────────────
def inspect_data_plane(mgmt_client) -> None:
    def _payment_user_id() -> str:
        return mgmt_client.get_payment_instrument(
            paymentManagerArn=MANAGER_ARN, paymentInstrumentId=PAYMENT_INSTRUMENT_ID, userId=USER_ID
        )["paymentInstrument"]["userId"]

    # GetPaymentSession — spending-limit state and remaining spend.
    resp = mgmt_client.get_payment_session(
        paymentManagerArn=MANAGER_ARN, paymentSessionId=PAYMENT_SESSION_ID, userId=USER_ID
    )
    s = resp.get("paymentSession", {})
    limit_amt = s.get("limits", {}).get("maxSpendAmount", {})
    avail = s.get("availableLimits", {}).get("availableSpendAmount", {})
    print("── Payment session ──")
    print(f"  Spending limit: {limit_amt.get('value', '?')} {limit_amt.get('currency', '')}")
    print(f"  Remaining:      {avail.get('value', '?')} {avail.get('currency', '')}")
    print(f"  Expires in:     {s.get('expiryTimeInMinutes', '?')} minutes")

    # GetPaymentInstrumentBalance — on-chain USDC balance.
    try:
        chain = "BASE" if PAYMENT_INSTRUMENT_NETWORK == "ETHEREUM" else "SOLANA"
        bal_resp = mgmt_client.get_payment_instrument_balance(
            paymentManagerArn=MANAGER_ARN,
            paymentConnectorId=PAYMENT_CONNECTOR_ID,
            paymentInstrumentId=PAYMENT_INSTRUMENT_ID,
            userId=_payment_user_id(),
            chain=chain,
            token="USDC",
        )
        bal = bal_resp.get("tokenBalance", {})
        amount = int(bal.get("amount", "0")) / (10 ** int(bal.get("decimals", 6)))
        print(f"\n── Wallet balance ({chain}) ──")
        print(f"  Wallet:  {WALLET_ADDRESS}")
        print(f"  Balance: {amount:.6f} {bal.get('token', 'USDC')}")
    except botocore.exceptions.ClientError as exc:
        print(f"\n  ⚠️  GetPaymentInstrumentBalance: {exc.response['Error']['Code']}")

    # ListPaymentInstruments — every instrument under this connector.
    try:
        insts = mgmt_client.list_payment_instruments(
            paymentManagerArn=MANAGER_ARN,
            paymentConnectorId=PAYMENT_CONNECTOR_ID,
            userId=_payment_user_id(),
            maxResults=20,
        ).get("paymentInstruments", [])
        print(f"\n── Payment instruments ({len(insts)}) ──")
        for it in insts:
            print(f"  {it.get('paymentInstrumentId')}  ({it.get('status', '?')})")
    except botocore.exceptions.ClientError as exc:
        print(f"\n  ⚠️  ListPaymentInstruments: {exc.response['Error']['Code']}")

    # ListPaymentSessions — every session under this manager.
    try:
        sess = mgmt_client.list_payment_sessions(
            paymentManagerArn=MANAGER_ARN,
            userId=USER_ID,
            maxResults=20,
        ).get("paymentSessions", [])
        print(f"\n── Payment sessions ({len(sess)}) ──")
        for se in sess:
            print(f"  {se.get('paymentSessionId')}  (expires in {se.get('expiryTimeInMinutes', '?')} min)")
    except botocore.exceptions.ClientError as exc:
        print(f"\n  ⚠️  ListPaymentSessions: {exc.response['Error']['Code']}")


# ── §10. Cleanup ─────────────────────────────────────────────────────────────
def _safe_delete(fn, label, **kwargs):
    try:
        fn(**kwargs)
        print(f"  ✅ Deleted: {label}")
    except botocore.exceptions.ClientError as exc:
        code = exc.response["Error"]["Code"]
        msg = exc.response["Error"].get("Message", "")
        if code == "ResourceNotFoundException" or (code == "AccessDeniedException" and "not found" in msg.lower()):
            print(f"  ⚠️  Not found: {label}")
        else:
            raise


def cleanup(cp_client, mgmt_client) -> None:
    payment_user_id = USER_ID
    try:
        payment_user_id = mgmt_client.get_payment_instrument(
            paymentManagerArn=MANAGER_ARN, paymentInstrumentId=PAYMENT_INSTRUMENT_ID, userId=USER_ID
        )["paymentInstrument"]["userId"]
    except Exception:  # noqa: BLE001
        pass

    if PAYMENT_SESSION_ID:
        _safe_delete(mgmt_client.delete_payment_session, f"Session {PAYMENT_SESSION_ID}",
                     paymentManagerArn=MANAGER_ARN, paymentSessionId=PAYMENT_SESSION_ID, userId=payment_user_id)
    if PAYMENT_INSTRUMENT_ID and PAYMENT_CONNECTOR_ID:
        _safe_delete(mgmt_client.delete_payment_instrument, f"Instrument {PAYMENT_INSTRUMENT_ID}",
                     paymentManagerArn=MANAGER_ARN, paymentConnectorId=PAYMENT_CONNECTOR_ID,
                     paymentInstrumentId=PAYMENT_INSTRUMENT_ID, userId=payment_user_id)
    if PAYMENT_CONNECTOR_ID:
        _safe_delete(cp_client.delete_payment_connector, f"Connector {PAYMENT_CONNECTOR_ID}",
                     paymentManagerId=MANAGER_ID, paymentConnectorId=PAYMENT_CONNECTOR_ID, clientToken=_client_token())
    _safe_delete(cp_client.delete_payment_manager, f"Manager {MANAGER_ID}",
                 paymentManagerId=MANAGER_ID, clientToken=_client_token())
    if CREDENTIAL_PROVIDER_ARN:
        _safe_delete(cp_client.delete_payment_credential_provider,
                     f"Credential provider {CREDENTIAL_PROVIDER_ARN.rsplit('/', 1)[-1]}",
                     name=CREDENTIAL_PROVIDER_ARN.rsplit("/", 1)[-1])

    write_env_updates({k: "" for k in (
        "MANAGER_ARN", "PAYMENT_CONNECTOR_ID", "CREDENTIAL_PROVIDER_ARN",
        "PAYMENT_INSTRUMENT_ID", "PAYMENT_SESSION_ID", "WALLET_ADDRESS",
    )})
    # nosec B603 — fixed command list (no shell, no untrusted input).
    subprocess.run(["bash", "test/integration/destroy-agent.sh"], cwd=HERE, check=False)  # noqa: S603
    print("\n✅ Cleanup complete.")


def main() -> None:
    print("=" * 72)
    print("  Pay for Secure Data (x402) — trust-gated agent")
    print("=" * 72)
    _run_env_check()

    # §3 — always runs; no AWS, no money.
    guardrail_demo()

    # §4 + §5 — provision payments resources.
    cp_client = build_control_client()
    setup_payments(cp_client)
    mgmt_session = assume_role(Session(region_name=AWS_REGION), MANAGEMENT_ROLE_ARN, "x402-secure-mgmt")
    mgmt_client = mgmt_session.client("bedrock-agentcore")
    setup_instrument_and_session(mgmt_client)

    # §6 — one-time onboarding gate. A live run cannot settle a payment until
    # BOTH delegated-signing layers are granted AND the wallet is funded, so
    # pause here (when a live run is requested) and wait for explicit
    # confirmation. This prevents ProcessPayment from failing on an unfunded /
    # undelegated wallet immediately after the session is created.
    onboarding_confirmed = False
    if _env_flag("RUN_LIVE") or _env_flag("RUN_LIVE_RUNTIME"):
        onboarding_confirmed = _confirm_section(
            "§6. One-time onboarding — complete before any live paid run",
            [
                "  A live run settles REAL USDC. Before continuing you MUST have:",
                "    1. Granted delegated signing at BOTH layers (project policy +",
                "       the per-wallet Wallet Hub grant printed above).",
                f"    2. Funded the wallet with USDC on {PAYMENT_INSTRUMENT_NETWORK} (Base):",
                f"         {WALLET_ADDRESS or '(see the address printed above)'}",
                "  Verify the wallet balance is non-zero before you continue.",
            ],
            "confirm delegation is granted and the wallet is funded, and continue",
        )
        if not onboarding_confirmed:
            print("\n↷ Onboarding not confirmed — skipping the live run and deploy.")
            print("   Grant delegation, fund the wallet, then re-run.")

    # §7 — live paid run. Gated on RUN_LIVE in .env (default off) AND on the
    # onboarding confirmation above. Each approved run settles REAL USDC twice
    # (the t54 x402-secure trust check and the target service call).
    if _env_flag("RUN_LIVE") and onboarding_confirmed:
        run_agent_live()
    elif not _env_flag("RUN_LIVE"):
        print("\n↷ §7 skipped — RUN_LIVE is not set in .env. Set RUN_LIVE=1 to run the")
        print("   live trust-gated flow (spends real USDC) after delegation + funding.")

    # §8 — deploy to runtime + live invoke. Gated on RUN_LIVE_RUNTIME in .env
    # AND the onboarding confirmation (the deployed runtime also spends real USDC).
    if _env_flag("RUN_LIVE_RUNTIME") and onboarding_confirmed:
        deploy_and_invoke_runtime()
    elif not _env_flag("RUN_LIVE_RUNTIME"):
        print("\n↷ §8 skipped — RUN_LIVE_RUNTIME is not set in .env. Set RUN_LIVE_RUNTIME=1")
        print("   to build + deploy the AgentCore Runtime and invoke it live.")

    # §9 — inspect.
    try:
        inspect_data_plane(mgmt_client)
    except botocore.exceptions.ClientError as exc:
        print(f"⚠️  Data-plane inspection skipped: {exc.response['Error']['Code']}")

    # §10 — cleanup (gated).
    if _confirm_section(
        "§10. Cleanup",
        ["  Revokes the session and deletes the instrument, connector, manager,",
         "  credential provider, and the agent runtime stack."],
        "tear everything down",
    ):
        cleanup(cp_client, mgmt_client)
    else:
        print("↷ Skipped cleanup — resources remain and continue to bill.")


if __name__ == "__main__":
    try:
        main()
    except botocore.exceptions.ClientError as exc:
        code = exc.response.get("Error", {}).get("Code", "Unknown")
        sys.exit(f"AWS API error: {code}. See local AWS logs for details.")
