def _client_token() -> str:
    """AgentCore payments requires clientToken >= 33 chars (idempotency token)."""
    return f"{uuid.uuid4()}-{uuid.uuid4().hex[:8]}"


def _safe_name(prefix: str) -> str:
    name = f"{prefix}{uuid.uuid4().hex[:8]}"
    assert re.match(r"^[a-zA-Z][a-zA-Z0-9]{0,47}$", name), name
    return name


def _env_flag(name: str) -> bool:
    """True if the named .env gate is set to 1/true/yes (default off)."""
    return os.environ.get(name, "0").strip().lower() in ("1", "true", "yes")


def _confirm_section(title: str, body_lines: list[str], action_label: str) -> bool:
    """Show a framed banner + body, then prompt: Enter to run, q + Enter to skip."""
    print("\n" + "=" * 72)
    print(f"  {title}")
    print("=" * 72)
    for line in body_lines:
        print(line)
    print(f"\n  ▶▶ Press Enter to {action_label}, or press q + Enter to skip.")
    return input("     [Enter to continue | q to skip] ").strip().lower() not in ("q", "quit", "skip", "n", "no")


